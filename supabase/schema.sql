revoke all on function public.is_site_admin() from public, anon;
grant execute on function public.is_site_admin() to authenticated;

create or replace function public.consume_api_rate_limit(
  p_scope text,
  p_identifier text,
  p_max_requests integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  allowed boolean;
begin
  if p_scope not in ('ai-admin', 'ai-public', 'contact-request')
    or p_max_requests < 1
    or p_max_requests > 100
    or p_window_seconds < 1
    or p_window_seconds > 86400
  then
    raise exception 'Invalid rate limit parameters';
  end if;

  insert into public.api_rate_limits (scope, identifier, window_started_at, request_count)
  values (p_scope, p_identifier, now(), 1)
  on conflict (scope, identifier) do update
  set
    request_count = case
      when api_rate_limits.window_started_at <= now() - make_interval(secs => p_window_seconds) then 1
      else api_rate_limits.request_count + 1
    end,
    window_started_at = case
      when api_rate_limits.window_started_at <= now() - make_interval(secs => p_window_seconds) then now()
      else api_rate_limits.window_started_at
    end;

  select request_count <= p_max_requests
  into allowed
  from public.api_rate_limits
  where scope = p_scope and identifier = p_identifier;

  delete from public.api_rate_limits
  where window_started_at < now() - interval '1 day';

  return allowed;
end;
$$;

revoke all on function public.consume_api_rate_limit(text, text, integer, integer) from public, anon, authenticated;
grant execute on function public.consume_api_rate_limit(text, text, integer, integer) to service_role;

drop policy if exists "Public can read site content" on public.site_content;
create policy "Public can read site content"
on public.site_content for select
to anon, authenticated
using (true);

drop policy if exists "Admins can insert site content" on public.site_content;
create policy "Admins can insert site content"
on public.site_content for insert
to authenticated
with check (public.is_site_admin() and auth.uid() = updated_by);

drop policy if exists "Admins can update site content" on public.site_content;
create policy "Admins can update site content"
on public.site_content for update
to authenticated
using (public.is_site_admin())
with check (public.is_site_admin() and auth.uid() = updated_by);

create or replace function public.set_site_content_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_site_content_updated_at on public.site_content;
create trigger set_site_content_updated_at
before update on public.site_content
for each row execute function public.set_site_content_updated_at();
